/**
 * The Lease Clause Decoder: the clauses that show up in a South Shore
 * commercial lease, each in plain English, with what each chair wants,
 * the red flags, the ask, and sample language a reader can recognize on
 * the page in front of them. Rendered at /lease-clauses/. Not legal
 * advice; the page says so and the tool builds the list of questions to
 * take to an attorney.
 */
export type ClauseGroup = 'rent' | 'term' | 'operating' | 'use' | 'risk' | 'exit' | 'build';

export interface LeaseClause {
  slug: string;
  name: string;
  group: ClauseGroup;
  /** One sentence: what the clause does. */
  plain: string;
  /** What a careful tenant pushes for. */
  tenant: string;
  /** What a careful landlord pushes for. */
  landlord: string;
  /** Language or structures that should slow a reader down. */
  redFlags: string[];
  /** The specific negotiation ask, phrased so it can be copied into an email. */
  ask: string;
  /** Recognizable sample language, paraphrased from typical forms. */
  sample: string;
  /** Glossary slugs to read next. */
  glossary: string[];
  /** How often it is worth fighting over, 1 (rarely) to 3 (always). */
  weight: 1 | 2 | 3;
}

