#!/usr/bin/env node
/**
 * Generates one verification worksheet per source in docs/verification/.
 *
 * Each worksheet lists everything on the site that rests on that source: the
 * ledger claims, and every sentence in a page, timeline or table that cites it.
 * A maintainer works through the sheet with the original document open.
 * The sheets are generated: edit the site, then re-run this script.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const outDir = join(root, 'docs', 'verification');

const { sources } = await import('../src/data/sources.ts');
const { claims } = await import('../src/data/claims.ts');
const { ped, hms } = await import('../src/data/timelines.ts');
const { comparison } = await import('../src/data/comparison.ts');

const strip = (s) => s
  .replace(/<Cite[^>]*\/>/g, '')
  .replace(/<(State|Grade)[^>]*\/>/g, '')
  .replace(/<[^>]+>/g, ' ')
  .replace(/\{[^{}]*\}/g, ' ')
  .replace(/&[a-z]+;/g, ' ')
  .replace(/\s+/g, ' ')
  .trim();

/** For each <Cite id="x"/> in a page, capture the text of the block it sits in. */
const uses = {}; // id -> [{ where, text }]
const push = (id, where, text) => { (uses[id] ??= []); if (text && !uses[id].some((u) => u.text === text)) uses[id].push({ where, text }); };

const pagesDir = join(root, 'src', 'pages');
for (const f of readdirSync(pagesDir).filter((f) => f.endsWith('.astro'))) {
  const body = readFileSync(join(pagesDir, f), 'utf8').replace(/^---[\s\S]*?---/, '');
  const page = f === 'index.astro' ? '/' : `/${f.replace('.astro', '')}/`;
  // Split into blocks at the elements that hold a complete statement.
  for (const block of body.split(/(?=<(?:p|li|tr|blockquote)\b)/)) {
    const ids = [...block.matchAll(/<Cite\s+id="([^"]+)"/g)].map((m) => m[1]);
    if (!ids.length) continue;
    const end = block.search(/<\/(?:p|li|tr|blockquote)>/);
    const text = strip(end > 0 ? block.slice(0, end) : block);
    for (const id of new Set(ids)) push(id, page, text);
  }
}
for (const [name, events, page] of [['Timeline', ped, '/program-for-evolutionary-dynamics/'], ['Timeline', hms, '/harvard-medical-school/']]) {
  for (const e of events) for (const c of e.cites) push(c.id, `${page} (${name}: ${e.date})`, `${e.title}. ${strip(e.body)}`);
}
for (const row of comparison.rows) {
  row.cells.forEach((cell, i) => cell.cites.forEach((id) => push(id, `/comparison/ (${row.element}; ${comparison.columns[i].split(':')[0]})`, strip(cell.text))));
}

if (existsSync(outDir)) rmSync(outDir, { recursive: true });
mkdirSync(outDir, { recursive: true });

const stateLabel = { intent: 'Stated intent', activity: 'Documented activity', verified: 'Verified implementation', none: 'Nothing on record' };
const index = [];

for (const [id, s] of Object.entries(sources)) {
  const mine = claims.filter((c) => c.sources.includes(id));
  const sentences = uses[id] ?? [];
  const named = mine.some((c) => /[A-Z][a-z]+ [A-Z][a-zí]+/.test(c.claim));
  const lines = [
    `# Verification worksheet: ${id}`,
    '',
    '> Generated by `scripts/worksheets.mjs`. Do not edit by hand; re-run the script after changing the site.',
    '',
    `**Source:** ${s.title}`,
    `**Publisher:** ${s.publisher}${s.author ? `  \n**Author:** ${s.author}` : ''}`,
    `**Date:** ${s.date ?? 'undated or recurring'}  `,
    `**Grade:** ${s.grade}  `,
    `**Original:** ${s.url ?? '(no link recorded)'}  `,
    `**Status:** ${s.checked ? `checked ${s.checked}` : 'PENDING CHECK'}`,
    '',
    s.note ? `**Note on this source:** ${s.note}\n` : '',
    '## Before you start',
    '',
    '- [ ] The link opens the publisher\'s own copy of the document.',
    '- [ ] Title, publisher and date in the register match the document.',
    '- [ ] The grade is right for this kind of document (see `/methodology/`).',
    s.grade === 'A1' && /complaint|letter from/i.test(s.title) ? '- [ ] Every use below describes its content as an allegation or assertion, not a finding.' : '',
    '',
    `## Ledger claims resting on this source (${mine.length})`,
    '',
    mine.length ? '' : '_None. This source is used for context or corroboration only._',
    ...mine.flatMap((c) => [
      `### ${c.id} · ${stateLabel[c.state]} · graded ${c.grade}`,
      '',
      `> ${c.claim}`,
      '',
      c.caveat ? `Caveat that must travel with it: ${c.caveat}\n` : '',
      c.sources.length > 1 ? `Also rests on: ${c.sources.filter((x) => x !== id).join(', ')}\n` : '',
      '- [ ] Found in the document. Page or section: ______',
      '- [ ] The document says no less and no more than the claim.',
      '- [ ] Figures, dates and names match exactly.',
      '- [ ] The evidence state is right, and not stronger than the document supports.',
      '',
    ]),
    `## Sentences on the site that cite this source (${sentences.length})`,
    '',
    sentences.length ? '' : '_None in page text. Cited only through the ledger._',
    ...sentences.flatMap((u, i) => [
      `**${i + 1}. ${u.where}**`,
      '',
      `> ${u.text}`,
      '',
      '- [ ] Supported by the document as written.',
      '',
    ]),
    '## Sign-off',
    '',
    '- [ ] Every box above is ticked, or the site has been corrected and this sheet regenerated.',
    `- [ ] \`checked\` set on \`${id}\` in \`src/data/sources.ts\`.`,
    '- [ ] Any wording change recorded in `src/data/updates.ts`.',
    '',
    'Checked by: ______________  Date: ______________',
    '',
  ].filter((l) => l !== '' || true).join('\n').replace(/\n{3,}/g, '\n\n');
  writeFileSync(join(outDir, `${id}.md`), lines);
  index.push({ id, grade: s.grade, claims: mine.length, sentences: sentences.length, named, checked: s.checked });
}

// Index, ordered by how much rests on each source.
index.sort((a, b) => (b.claims * 3 + b.sentences) - (a.claims * 3 + a.sentences));
const table = [
  '# Verification worksheets',
  '',
  '> Generated by `scripts/worksheets.mjs`.',
  '',
  'One sheet per source, ordered by how much of the site rests on it. Work from the top.',
  'Sources whose claims name people are marked and should be done first within each band.',
  '',
  `**Progress:** ${index.filter((r) => r.checked).length} of ${index.length} sources checked.`,
  '',
  '| # | Source | Grade | Ledger claims | Citing sentences | Names people | Status |',
  '|---|---|---|---|---|---|---|',
  ...index.map((r, i) => `| ${i + 1} | [${r.id}](${r.id}.md) | ${r.grade} | ${r.claims} | ${r.sentences} | ${r.named ? 'yes' : ''} | ${r.checked ? `checked ${r.checked}` : 'pending'} |`),
  '',
].join('\n');
writeFileSync(join(outDir, 'README.md'), table);
console.log(`Wrote ${index.length} worksheets and an index to docs/verification/`);
