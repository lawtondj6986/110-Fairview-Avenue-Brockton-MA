#!/usr/bin/env node
/**
 * Drafts one right-of-reply letter per person or body named on the site,
 * into docs/right-of-reply/. Each letter quotes exactly what the site says
 * about the recipient (from the named index and the claim ledger), invites a
 * correction or a response, and says what will happen to a reply.
 *
 *   node scripts/right-of-reply.mjs
 *
 * These are DRAFTS for a person to review, address and send. Nothing is sent
 * by this script. Regenerate after any change to the ledger or named index,
 * and never send a letter whose statements have not yet been verified against
 * their sources: check first, then write to people.
 */
import { writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const outDir = join(root, 'docs', 'right-of-reply');

const { named, roleLabels } = await import('../src/data/named.ts');
const { claims } = await import('../src/data/claims.ts');
const { sources } = await import('../src/data/sources.ts');
const { site } = await import('../src/config.ts');

const slug = (s) => s.toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const stateLabel = { intent: 'stated intent or allegation', activity: 'documented activity', verified: 'confirmed by an official finding', none: 'a statement that no record was found' };
const byId = new Map(claims.map((c) => [c.id, c]));

/** People who cannot be written to, with the reason recorded in the index instead of a letter. */
const NO_LETTER = { 'Jeffrey Epstein': 'Deceased (2019). No letter is drafted. Consider whether the estate should be offered a reply on the U.S. Virgin Islands material.' };

/** Whether every source behind every claim about this entry has been checked. */
const verified = (n) => n.claims.every((id) => byId.get(id)?.sources.every((s) => sources[s]?.checked));

export function draftLetter(n) {
  const mine = n.claims.map((id) => byId.get(id)).filter(Boolean);
  const isBody = n.role === 'institution';
  const salutation = isBody ? `To the press office, ${n.name}` : `Dear ${n.name}`;
  const lines = [
    `# Right of reply: ${n.name}`,
    '',
    '> DRAFT generated by `scripts/right-of-reply.mjs`. Review, address and send by hand. Do not send until',
    '> every statement below has been verified against its source.',
    '',
    `**Role on the site:** ${roleLabels[n.role]}  `,
    `**Verification status of the statements below:** ${verified(n) ? 'all sources checked' : 'NOT YET VERIFIED. Do not send.'}  `,
    `**Send to:** ______________________ (a direct, private address; never a public post)  `,
    `**Date sent:** ____________  **Reply requested by:** ____________ (allow at least ten working days)`,
    '',
    '---',
    '',
    `${salutation},`,
    '',
    `I am writing on behalf of ${site.name}, an independent reference site that summarizes what public`,
    'records and published reporting show about donor influence and institutional access at Harvard',
    'University. The site is not affiliated with the University.',
    '',
    isBody
      ? `The site refers to ${n.name}. Before it is published, I would like to give you the opportunity to correct any error and to respond.`
      : 'You are named on the site. Before it is published, I would like to give you the opportunity to correct any error and to respond.',
    '',
    '## Why your name appears',
    '',
    n.why,
    '',
    '## What the site says',
    '',
    'The site summarizes the record as follows:',
    '',
    `> ${n.recordSays}`,
    '',
    'It also states what the record does not say:',
    '',
    `> ${n.recordDoesNotSay}`,
    '',
    ...(n.response ? ['It records this response from you:', '', `> ${n.response}`, ''] : []),
    '## The individual statements and their sources',
    '',
    ...mine.flatMap((c, i) => [
      `${i + 1}. ${c.claim}`,
      `   - The site classes this as: ${stateLabel[c.state]}.`,
      ...(c.caveat ? [`   - It adds this caveat: ${c.caveat}`] : []),
      `   - Source${c.sources.length > 1 ? 's' : ''}: ${c.sources.map((id) => `${sources[id].title} (${sources[id].publisher}${sources[id].date ? `, ${sources[id].date.slice(0, 4)}` : ''})${sources[id].url ? ` ${sources[id].url}` : ''}`).join('; ')}`,
      '',
    ]),
    `These statements appear on: ${n.pages.map((p) => `${site.url}${p}`).join(', ')}`,
    '',
    '## What I am asking',
    '',
    '1. Is anything above inaccurate? If so, please tell me what is wrong and, if you can, point me to a',
    '   public source I can check.',
    '2. Is anything missing that a fair account should include?',
    n.response
      ? '3. Is the response recorded above still your position, and is it accurately stated?'
      : '3. Would you like a response from you to appear beside these statements? If so, please send the wording.',
    '',
    '## What happens to your reply',
    '',
    '- A confirmed error will be corrected before publication, and afterwards at any time, with the',
    '  correction recorded in the site\'s public update log.',
    '- A response you send for publication will be placed beside the statements it answers.',
    '- Anything you mark as not for publication will not be published or quoted.',
    '- If I do not hear from you, the site will say nothing about that; it will not describe you as having',
    '  declined to comment unless you tell me that is your answer.',
    '',
    `You can reach me at ${site.correctionsEmail}. The site's corrections policy is at ${site.url}/about/#corrections.`,
    '',
    'Yours sincerely,',
    '',
    '______________________',
    `for ${site.publisher}`,
    '',
    '---',
    '',
    '## Record of this contact (keep with the letter)',
    '',
    '- [ ] Statements above verified against their sources before sending',
    '- [ ] Letter sent on ____________ to ____________ by ____________',
    '- [ ] Reply received on ____________ / no reply by the date given',
    '- [ ] Corrections made: ____________ (and logged in `src/data/updates.ts`)',
    '- [ ] Response added to the page and to `src/data/named.ts`',
    '',
  ];
  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (existsSync(outDir)) rmSync(outDir, { recursive: true });
  mkdirSync(outDir, { recursive: true });
  const rows = [];
  for (const n of [...named].sort((a, b) => a.sort.localeCompare(b.sort))) {
    if (NO_LETTER[n.name]) { rows.push(`| ${n.name} | ${roleLabels[n.role]} | none | ${NO_LETTER[n.name]} |`); continue; }
    const file = `${slug(n.sort)}.md`;
    writeFileSync(join(outDir, file), draftLetter(n));
    rows.push(`| ${n.name} | ${roleLabels[n.role]} | [draft](${file}) | ${verified(n) ? 'Statements verified. Ready to review and send.' : 'Statements not yet verified. Do not send.'} |`);
  }
  const index = [
    '# Right-of-reply letters',
    '',
    '> Generated by `scripts/right-of-reply.mjs`. Drafts only: nothing has been sent.',
    '',
    'One draft per person or body named on the site. The launch checklist requires that each named living',
    'person is offered a reply, or that a decision not to write is recorded with the reason.',
    '',
    'Order of work: verify the sources first (`npm run verify:build`), regenerate these drafts, then review',
    'each letter, find a direct private address, and send. People named only as recipients of a gift should be',
    'written to as carefully as anyone else: the letter tells them exactly how little the site says.',
    '',
    '| Name | Role | Letter | Status |',
    '|---|---|---|---|',
    ...rows,
    '',
    '## Decisions not to write',
    '',
    'Record here anyone you decide not to contact, and why.',
    '',
    '| Name | Reason | Decided by | Date |',
    '|---|---|---|---|',
    '| | | | |',
    '',
  ].join('\n');
  writeFileSync(join(outDir, 'README.md'), index);
  console.log(`Right-of-reply drafts: ${rows.length - Object.keys(NO_LETTER).length} letters -> docs/right-of-reply/`);
}
