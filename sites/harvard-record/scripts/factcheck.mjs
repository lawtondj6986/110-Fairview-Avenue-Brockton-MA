#!/usr/bin/env node
/**
 * Fact-check register for the reference content (glossary, law explainers, guides).
 *
 * The reference content was written from general knowledge. Most of it is
 * explanation, but some sentences make checkable factual statements: numbers,
 * dates, dollar thresholds, deadlines, legal citations, and absolute words
 * such as "never" or "every state". This script finds those sentences and
 * writes one worksheet per file into docs/factcheck/, plus an index ordered by
 * risk, so an editor can check them against official texts.
 *
 *   node scripts/factcheck.mjs            write the worksheets
 *   node scripts/factcheck.mjs --summary  print counts only
 *
 * The worksheets are generated. Edit the content, then re-run.
 */
import { mkdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCollection } from './lib/frontmatter.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const outDir = join(root, 'docs', 'factcheck');
const summaryOnly = process.argv.includes('--summary');

import { RULES, sentences, flags } from './lib/factcheck-rules.mjs';

const weightOf = (fl) => fl.reduce((n, r) => n + r.weight, 0);
const collectionWeight = { law: 3, glossary: 1, guides: 1 };

const items = [];
for (const name of ['law', 'glossary', 'guides']) {
  for (const e of loadCollection(root, name)) {
    if (e.data.series === 'Worked examples') continue; // checked through the claim ledger instead
    const found = [];
    for (const s of sentences(e.body)) {
      const fl = flags(s);
      if (fl.length && !(fl.length === 1 && fl[0].id === 'count' && /^\d+\.?\s/.test(s))) found.push({ s, fl });
    }
    const urls = [...new Set([...e.text.matchAll(/https:\/\/[^\s"')>\]]+/g)].map((m) => m[0].replace(/[.,;]+$/, '')))];
    const risk = found.reduce((n, f) => n + weightOf(f.fl), 0) * collectionWeight[name] + urls.length * 2;
    items.push({ name, file: e.file, slug: e.slug, title: e.data.term ?? e.data.title, category: e.data.category ?? e.data.series ?? e.data.jurisdiction, found, urls, risk });
  }
}
items.sort((a, b) => b.risk - a.risk);

const totals = {
  files: items.length,
  withChecks: items.filter((i) => i.found.length || i.urls.length).length,
  sentences: items.reduce((n, i) => n + i.found.length, 0),
  urls: items.reduce((n, i) => n + i.urls.length, 0),
  byRule: Object.fromEntries(RULES.map((r) => [r.id, items.reduce((n, i) => n + i.found.filter((f) => f.fl.some((x) => x.id === r.id)).length, 0)])),
};

if (summaryOnly) {
  console.log(JSON.stringify(totals, null, 2));
  process.exit(0);
}

if (existsSync(outDir)) rmSync(outDir, { recursive: true });
for (const n of ['law', 'glossary', 'guides']) mkdirSync(join(outDir, n), { recursive: true });

const pathOf = { law: 'law', glossary: 'glossary', guides: 'guides' };
for (const i of items) {
  if (!i.found.length && !i.urls.length) continue;
  const lines = [
    `# Fact-check: ${i.title}`,
    '',
    '> Generated by `scripts/factcheck.mjs`. Do not edit by hand; fix the content file and re-run.',
    '',
    `**File:** \`src/content/${i.name}/${i.file}\`  `,
    `**Page:** \`/${pathOf[i.name]}/${i.slug}/\`  `,
    `**Group:** ${i.category}  `,
    `**Risk score:** ${i.risk}`,
    '',
    'For each statement: find it in an official or authoritative text, then tick it, correct the file,',
    'or soften the sentence so it no longer asserts what cannot be confirmed. Record the source you used.',
    '',
    `## Statements to check (${i.found.length})`,
    '',
    ...(i.found.length ? i.found.flatMap((f, k) => [
      `${k + 1}. ${f.s}`,
      `   - Flags: ${f.fl.map((r) => r.label).join(', ')}`,
      '   - [ ] Confirmed. Source: ______',
      '',
    ]) : ['_None flagged._', '']),
    `## Links to open (${i.urls.length})`,
    '',
    ...(i.urls.length ? i.urls.map((u) => `- [ ] ${u}`) : ['_None._']),
    '',
    '## Sign-off',
    '',
    'Checked by: ______________  Date: ______________',
    '',
  ];
  writeFileSync(join(outDir, i.name, `${i.slug}.md`), lines.join('\n'));
}

const withWork = items.filter((i) => i.found.length || i.urls.length);
const index = [
  '# Fact-check register for the reference content',
  '',
  '> Generated by `scripts/factcheck.mjs`.',
  '',
  'The glossary, law explainers and guides were written from general knowledge, without access to the',
  'statutes or agency pages. This register lists every sentence that makes a checkable factual statement',
  '(a number, date, dollar threshold, deadline, legal citation, recent change or absolute claim) and every',
  'external link. Work from the top: the list is ordered by risk, and law explainers weigh most.',
  '',
  `**Scope:** ${totals.files} files; ${withWork.length} have something to check; ${totals.sentences} flagged statements; ${totals.urls} links.`,
  '',
  '| Flag | Statements |',
  '|---|---|',
  ...RULES.map((r) => `| ${r.label} | ${totals.byRule[r.id]} |`),
  '',
  '| # | File | Group | Statements | Links | Risk |',
  '|---|---|---|---|---|---|',
  ...withWork.map((i, k) => `| ${k + 1} | [${i.name}/${i.slug}](${i.name}/${i.slug}.md) | ${i.category} | ${i.found.length} | ${i.urls.length} | ${i.risk} |`),
  '',
];
writeFileSync(join(outDir, 'README.md'), index.join('\n'));
console.log(`Fact-check register: ${withWork.length} worksheets, ${totals.sentences} statements, ${totals.urls} links -> docs/factcheck/`);
